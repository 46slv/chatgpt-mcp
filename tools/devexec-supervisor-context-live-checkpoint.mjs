import os from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {buildSupervisorCheckpoint,buildSupervisorRehydratePack} from './devexec-supervisor-context-governor.mjs';
import {persistSupervisorCheckpoint,loadSupervisorCheckpoint,appendSupervisorContextEvent} from './devexec-supervisor-context-runtime.mjs';
const run=(a)=>{const r=spawnSync('git',a,{encoding:'utf8',windowsHide:true});if(r.status!==0)throw new Error(r.stderr||'git failed');return (r.stdout||'').trim();};
const mission='DEV-EXEC-CONTINUE-1787234698189-c09185';
const runId='DEV-EXEC-CONTINUE-1787260998276-24cf61';
const localHead=run(['rev-parse','HEAD']);
const branch=run(['branch','--show-current']);
const remote=(run(['ls-remote','https://github.com/46slv/chatgpt-mcp.git','refs/heads/probe/windows-local']).split(/\s+/)[0]||'');
const dir=path.join(process.env.LOCALAPPDATA||path.join(os.homedir(),'AppData','Local'),'ChatGPTMCPProbe','supervisor-context');
const cp=buildSupervisorCheckpoint({mission_id:mission,run_id:runId,target:{target_id:'current-chat'},notion_authority:{page_id:'3c1fd279-a6f3-81e3-8314-ef8065660a90',read_at:'2026-08-21T06:22:29+09:00'},git:{branch,local_head:localHead,remote_branch:'probe/windows-local',remote_head:remote},completed_evidence:['GITHUB_DEDICATED_BRANCH_VERIFIED','SUPERVISOR_CONTEXT_GOVERNOR_V0_TEST_PASS','SUPERVISOR_CONTEXT_RUNTIME_V0_TEST_PASS'],next_goal:'Integrate bounded Supervisor checkpoint and rotation lifecycle without changing mission identity.',constraints:['fresh Notion and Git override old conversation history','never rotate ambiguous in-flight execution','preserve messy worktree','no broad staging']});
const file=persistSupervisorCheckpoint(dir,cp);
const loaded=loadSupervisorCheckpoint(dir,mission);
const pack=buildSupervisorRehydratePack({checkpoint:loaded,freshNotion:cp.notion_authority,freshGit:cp.git});
appendSupervisorContextEvent(dir,mission,{decision:'CHECKPOINT',reason:'SUPERVISOR_GOVERNOR_MVP_READY',run_id:runId});
if(pack.mission_id!==mission)throw new Error('MISSION_CONTINUITY_MISMATCH');
console.log('CHECKPOINT_FILE='+file);
console.log('MISSION_ID='+pack.mission_id);
console.log('LOCAL_HEAD='+localHead);
console.log('REMOTE_HEAD='+remote);
console.log('DEVEXEC_SUPERVISOR_CONTEXT_LIVE_CHECKPOINT_V0_PASS');
