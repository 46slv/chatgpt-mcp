import os from 'node:os';
import path from 'node:path';
import {loadRegistry} from './target-registry.mjs';
import {buildSupervisorRotationPlan} from './devexec-supervisor-rotation-plan.mjs';
import {persistRotationPlan,loadRotationPlan} from './devexec-supervisor-rotation-runtime.mjs';
const mission='DEV-EXEC-CONTINUE-1787234698189-c09185';
const run='DEV-EXEC-CONTINUE-1787260998276-24cf61';
const base=process.env.LOCALAPPDATA||path.join(os.homedir(),'AppData','Local');
const dir=path.join(base,'ChatGPTMCPProbe','supervisor-context');
const registry=loadRegistry(); const before=registry.default_target;
const plan=buildSupervisorRotationPlan({mission_id:mission,run_id:run,current_target_id:'current-chat',next_generation:2,checkpoint_file:path.join(dir,mission+'.supervisor-checkpoint.json'),ambiguous_in_flight:false});
const file=persistRotationPlan(dir,plan); const loaded=loadRotationPlan(dir,mission);
const after=loadRegistry().default_target;
if(before!==after)throw new Error('ACTIVE_TARGET_MUTATED_DURING_IN_FLIGHT_PLAN');
if(loaded.state!=='WAIT_RUN_BOUNDARY')throw new Error('ROTATION_PLAN_STATE_MISMATCH');
console.log('ROTATION_PLAN_FILE='+file);
console.log('ACTIVE_TARGET='+after);
console.log('ROTATION_STATE='+loaded.state);
console.log('DEVEXEC_SUPERVISOR_LIVE_ROTATION_PLAN_V0_PASS');
